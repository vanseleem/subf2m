function _ext(n) { return n.match(/(\.[^.]+)$/)?.[1]?.toLowerCase() ?? ''; }
function _looksLikeSub(t) {
  return typeof t === 'string' && t.length > 40 && /(?:^|\n)\s*(?:\d+\s*\n)?\s*\d{1,2}:\d{2}:\d{2}[,.]\d{3}\s*-->\s*\d{1,2}:\d{2}:\d{2}[,.]\d{3}/m.test(t);
}
function _looksArabic(t) {
  return /[\u0600-\u06FF]/.test(t);
}
function decodeSubtitle(buf) {
  if (!Buffer.isBuffer(buf)) return null;
  let offset = 0;
  if (buf[0] === 0xEF && buf[1] === 0xBB && buf[2] === 0xBF) offset = 3;
  const u8 = buf.slice(offset);
  const utf8 = u8.toString('utf8');
  if (_looksLikeSub(utf8) && !utf8.includes('\uFFFD')) return utf8;
  if (typeof TextDecoder === 'function') {
    const encodings = ['utf-8', 'utf-16le', 'windows-1256', 'windows-1252', 'iso-8859-1'];
    for (const enc of encodings) {
      try {
        const t = new TextDecoder(enc, { fatal: false }).decode(u8);
        if (_looksLikeSub(t) && !t.includes('\uFFFD')) return t;
      } catch (_) {}
    }
  }
  const latin = u8.toString('latin1');
  return _looksLikeSub(latin) ? latin : null;
}
function validateSubtitleText(text) {
  if (!_looksLikeSub(text)) return { ok:false, reason:'not-subtitle' };
  const cues = text.match(/-->?/g)?.length || 0;
  if (cues < 1) return { ok:false, reason:'no-cues' };
  const bad = (text.match(/\uFFFD/g) || []).length;
  if (bad > 5) return { ok:false, reason:'encoding' };
  return { ok:true, cues, arabic:_looksArabic(text) };
}

function _extractFromZip(buf) {
  try {
    const zip = new AdmZip(buf);
    const rank = { '.srt':0, '.vtt':1, '.ass':2, '.ssa':3 };
    const files = zip.getEntries().filter(e => {
      const n = e.entryName.toLowerCase();
      return !e.isDirectory && !n.startsWith('__macosx') && Object.keys(rank).some(x => n.endsWith(x));
    }).sort((a,b) => (rank[_ext(a.entryName)] ?? 9) - (rank[_ext(b.entryName)] ?? 9));
    let fallback = null;
    for (const f of files) {
      const raw = zip.readFile(f);
      if (!raw) continue;
      const text = decodeSubtitle(raw);
      if (!text) continue;
      if (!fallback) fallback = text;
      const v = validateSubtitleText(text);
      if (v.ok) return text;
    }
    return fallback;
  } catch (_) { return null; }
}
function _tryDirect(buf) { const t = decodeSubtitle(buf); return t && validateSubtitleText(t).ok ? t : null; }

async function fetchSRT(downloadUrl) {
  const ck = `srt3:${downloadUrl}`;
  const hit = cacheGet(ck);
  if (hit !== null) return hit;
  try {
    const buf = await getBinary(downloadUrl);
    if (!buf) return null;
    const content = _extractFromZip(buf) ?? _tryDirect(buf);
    if (!content) return null;
    cacheSet(ck, content);
    return content;
  } catch (_) { return null; }
}

