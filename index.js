function _request(urlStr, opts = {}, redirects = 0) {
  return new Promise((resolve, reject) => {
    if (!urlStr || redirects > MAX_REDIRECTS) return reject(new Error('Invalid redirect chain'));
    let parsed;
    try { parsed = new URL(urlStr); } catch (_) { return reject(new Error('Invalid URL')); }
    const lib = parsed.protocol === 'https:' ? https : http;
    const timeout = opts.timeout || REQ_TIMEOUT;
    const maxBytes = opts.maxBytes || MAX_BODY_BYTES;
    const reqOpts = {
      hostname: parsed.hostname,
      port: parsed.port || (parsed.protocol === 'https:' ? 443 : 80),
      path: parsed.pathname + parsed.search,
      method: 'GET',
      headers: {
        'User-Agent': UA,
        'Accept': opts.binary ? 'application/zip,application/octet-stream,*/*' : 'text/html,application/xhtml+xml,*/*;q=0.8',
        'Accept-Language': opts.lang === 'arabic' ? 'ar,en-US;q=0.8,en;q=0.6' : 'en-US,en;q=0.9',
        'Accept-Encoding': 'gzip, deflate, br',
        'Referer': `${BASE}/`,
        'Connection': 'keep-alive',
        'Cache-Control': 'no-cache',
        'Upgrade-Insecure-Requests': '1',
        ...(opts.headers || {}),
      },
    };
    const req = lib.request(reqOpts, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        const next = new URL(res.headers.location, urlStr).toString();
        res.resume();
        return _request(next, opts, redirects + 1).then(resolve).catch(reject);
      }
      if (res.statusCode === 404) { res.resume(); return resolve(null); }
      if (res.statusCode !== 200) { res.resume(); return resolve(null); }
      let total = 0;
      const chunks = [];
      let stream = res;
      const enc = String(res.headers['content-encoding'] || '').toLowerCase();
      try {
        if (enc.includes('gzip')) stream = res.pipe(zlib.createGunzip());
        else if (enc.includes('br')) stream = res.pipe(zlib.createBrotliDecompress());
        else if (enc.includes('deflate')) stream = res.pipe(zlib.createInflate());
      } catch (e) { res.resume(); return reject(e); }
      stream.on('data', c => {
        total += c.length;
        if (total > maxBytes) {
          stream.destroy(new Error('Response too large'));
          return;
        }
        chunks.push(c);
      });
      stream.on('end', () => {
        const buf = Buffer.concat(chunks);
        resolve(opts.binary ? buf : buf.toString('utf8'));
      });
      stream.on('error', reject);
    });
    req.setTimeout(timeout, () => { req.destroy(new Error('Timeout')); });
    req.on('error', reject);
    req.end();
  });
}

async function getHTML(url, tries = 3, lang = 'english') {
  for (let i = 0; i < tries; i++) {
    try {
      const r = await _request(url, { timeout: REQ_TIMEOUT, lang });
      if (r !== null) return r;
    } catch (_) {}
    if (i < tries - 1) await sleep(700 * (i + 1));
  }
  return null;
}

