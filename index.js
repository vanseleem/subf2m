function extractSubtitleId(href) {
  if (!href) return null;
  const m = String(href).match(/\/(\d+)\/?$/);
  return m ? m[1] : null;
}
function normalizeDetailUrl(href, lang) {
  if (!href || !href.includes(`/${lang}/`)) return null;
  const id = extractSubtitleId(href);
  if (!id) return null;
  return href.startsWith('http') ? href : `${BASE}${href}`;
}

function _extractItem($, el, lang, out) {
  const $el = $(el);
  const rawText = _clean($el.text());
  let detailHref = null;
  $el.find('a[href]').each((_, a) => {
    const h = $(a).attr('href') || '';
    if (!detailHref && h.includes(`/${lang}/`)) detailHref = normalizeDetailUrl(h, lang);
  });
  if (!detailHref) return;
  const hLow = detailHref.toLowerCase();
  if (OTHER_LANGS.some(ol => hLow.includes(`/${ol}/`))) return;
  const subId = extractSubtitleId(detailHref);
  if (!subId) return;
  const isGood = (
    $el.find('.green-icon, .positive-icon').length > 0 ||
    $el.find('img[alt="good"], img[alt="Positive"], img[alt="positive"]').length > 0 ||
    $el.hasClass('good') || $el.hasClass('positive') || /\bgood\b/i.test($el.attr('class') || '')
  );
  const comment = _clean($el.find('p.comment, .comment').first().text());
  const releaseLines = $el.find('.r li, ul.release li, ul.scrolllist li, ul li').map((_, li) => _clean($(li).text())).get().filter(Boolean);
  const releaseInfo = (releaseLines.join(' | ') || rawText).substring(0, 240);
  if (isAISub(`${comment} ${releaseInfo}`)) return;
  out.push({ subId, detailUrl: detailHref, isGood, releaseInfo, comment, authorNote: '', lang, goodVotes: 0, badVotes: 0, downloads: 0, _rawText: rawText });
}

async function mapLimit(items, limit, fn) {
  const out = new Array(items.length);
  let next = 0;
  async function worker() {
    while (true) {
      const i = next++;
      if (i >= items.length) return;
      try { out[i] = await fn(items[i], i); } catch (_) { out[i] = null; }
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return out;
}

async function _enrichSub(sub) {
  const ck = `det3:${sub.subId}`;
  const hit = cacheGet(ck);
  if (hit !== null) return hit.__aiBlocked ? null : { ...sub, ...hit };
  const html = await getHTML(sub.detailUrl, 2, sub.lang);
  if (!html) { cacheSet(ck, sub); return sub; }
  const $ = cheerio.load(html);
  const txt = $.root().text();
  const goodVotes = +(txt.match(/voted\s+as\s+good\s+by[:\s]*(\d+)/i)?.[1] ?? 0);
  const badVotes = +(txt.match(/voted\s+as\s+bad\s+by[:\s]*(\d+)/i)?.[1] ?? 0);
  const downloads = +(txt.match(/downloads?[:\s]*(\d[\d,]*)/i)?.[1]?.replace(/,/g,'') ?? 0);
  const ratio = goodVotes + badVotes >= 3 ? goodVotes / (goodVotes + badVotes) : null;
  const authorNote = _clean($('p.comment, .comment, .notes, .author-comment').first().text());
  const relLines = $('ul.release li, .release-names li, ul.scrolllist li, .release li').map((_, e) => _clean($(e).text())).get().filter(Boolean);
  const releaseInfo = (relLines.length ? relLines.join(' | ') : sub.releaseInfo).substring(0, 300);
  if (isAISub(`${authorNote} ${releaseInfo} ${sub.comment}`)) {
    cacheSet(ck, { __aiBlocked: true }, true);
    return null;
  }
  const enriched = { ...sub, releaseInfo, goodVotes, badVotes, downloads, isGood: sub.isGood || (ratio !== null && ratio >= 0.70 && goodVotes >= 2), authorNote };
  cacheSet(ck, enriched);
  return enriched;
}

async function getSubsList(slug, lang, season, episode) {
  if (!ALLOWED_LANGS.has(lang)) return [];
  // IMPORTANT: season is part of the cache key. The old implementation could collide S01E03 with S02E03.
  const ck = `list3:${slug}:${lang}:${season ?? 0}:${episode ?? 0}`;
  const hit = cacheGet(ck);
  if (hit !== null) return hit;
  const html = await getHTML(`${BASE}/subtitles/${slug}/${lang}`, 3, lang);
  if (!html) { cacheSet(ck, [], true); return []; }
  const $ = cheerio.load(html);
  const raw = [];
  $('li.item').each((_, el) => _extractItem($, el, lang, raw));
  if (!raw.length) $('tr, .subtitle-item, .item').each((_, el) => _extractItem($, el, lang, raw));
  if (!raw.length) {
    $('a[href]').each((_, a) => {
      const href = $(a).attr('href') || '';
      if (!href.includes(`/${lang}/`)) return;
      const detailUrl = normalizeDetailUrl(href, lang);
      if (!detailUrl) return;
      const subId = extractSubtitleId(detailUrl);
      if (!subId) return;
      raw.push({ subId, detailUrl, isGood:false, releaseInfo:'', comment:'', authorNote:'', lang, goodVotes:0, badVotes:0, downloads:0, _rawText:_clean($(a).text()) });
    });
  }

  const unique = [];
  const seen = new Set();
  for (const s of raw) if (!seen.has(s.subId)) { seen.add(s.subId); unique.push(s); }

  // Filter exact episode when the site gives us a recognizable episode token. If nothing matches,
  // retain the full candidate pool instead of returning an empty result.
  let candidates = unique;
  if (season != null && episode != null) {
    const exact = unique.filter(s => {
      const p = parseRelease(`${s._rawText} ${s.releaseInfo}`);
      return p.season === Number(season) && p.episode === Number(episode);
    });
    if (exact.length) candidates = exact;
  }

  // Do not throw away candidates before AI filtering. Enrich in batches and keep going until
  // enough human candidates are found or the hard limit is reached.
  const enriched = [];
  for (let i = 0; i < candidates.length && enriched.length < MAX_DETAIL; i += DETAIL_CONCURRENCY) {
    const batch = candidates.slice(i, i + DETAIL_CONCURRENCY);
    const got = await mapLimit(batch, DETAIL_CONCURRENCY, _enrichSub);
    for (const s of got) if (s && !isAISub(`${s.releaseInfo} ${s.comment} ${s.authorNote}`)) enriched.push(s);
    if (i + DETAIL_CONCURRENCY >= MIN_DETAIL && enriched.length >= Math.min(MAX_PER_LANG * 3, 6)) break;
  }
  cacheSet(ck, enriched);
  return enriched;
}

